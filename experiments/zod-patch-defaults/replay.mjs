import assert from 'node:assert/strict';
import {z} from 'zod';
import {createRequire} from 'node:module';
import {Create, Patch} from './settings.mjs';
assert.equal(createRequire(import.meta.url)('zod/package.json').version, '4.6.7');
const Settings=z.object({theme:z.string().default('light'),fontSize:z.number().default(14)});
const input={fontSize:16};
const stored={theme:'dark',fontSize:14};
const original=Settings.partial().parse(input);
const exact=Settings.exactPartial().parse(input);
const repaired=Patch.parse(input);
const explicitRemoval=Settings.extend({theme:Settings.shape.theme.removeDefault(),fontSize:Settings.shape.fontSize.removeDefault()}).partial().parse(input);
const strip=(f)=>f instanceof z.ZodOptional||f instanceof z.ZodDefault?strip(f.unwrap()):f;
const wrapped=z.object({a:z.string().default('x').nullable(),b:z.number()});
const helperResult=z.object(Object.fromEntries(Object.entries(wrapped.shape).map(([k,v])=>[k,strip(v)]))).partial().parse({b:1});
assert.deepEqual(original,{theme:'light',fontSize:16});
assert.deepEqual(exact,original);assert.deepEqual(repaired,input);assert.deepEqual(explicitRemoval,input);
assert.deepEqual(Create.parse({}),{theme:'light',fontSize:14});assert.deepEqual(Patch.parse({}),{});
assert.equal(Patch.safeParse({fontSize:'16'}).success,false);
assert.deepEqual(helperResult,{a:'x',b:1});
console.log(JSON.stringify({original,exact,originalMerged:{...stored,...original},repaired,repairedMerged:{...stored,...repaired},explicitRemoval,createDefaults:Create.parse({}),emptyPatch:Patch.parse({}),invalidFontRejected:!Patch.safeParse({fontSize:'16'}).success,wrappedHelperResult:helperResult},null,2));
