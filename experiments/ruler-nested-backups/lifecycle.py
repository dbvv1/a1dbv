#!/usr/bin/env python3
"""Replay #775 against the built CLI using only task-owned synthetic projects."""
import hashlib, json, os, pathlib, subprocess, sys
if len(sys.argv) != 3:
    raise SystemExit('Usage: python lifecycle.py /absolute/path/to/dist/cli/index.js /new/output/directory')
CLI = pathlib.Path(sys.argv[1]).resolve(strict=True)
OUT = pathlib.Path(sys.argv[2]).resolve()
OUT.mkdir(parents=True, exist_ok=False)
(OUT / '_home').mkdir()
(OUT / '_tmp').mkdir()
ENV = os.environ.copy()
ENV.update(HOME=str(OUT/'_home'), XDG_CONFIG_HOME=str(OUT/'_home/.config'), TMPDIR=str(OUT/'_tmp'))
RESULTS = []
MARKER = '<!-- Generated by Ruler -->'
PROVENANCE = MARKER + '\nBackup generated by Ruler\n'

def write(p, text):
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text)

def read(p):
    return p.read_text() if p.exists() else None

def snapshot(project, dest):
    files = {str(p.relative_to(project)): p.read_text() for p in sorted(project.rglob('*')) if p.is_file()}
    dest.write_text(json.dumps(files, indent=2, ensure_ascii=False)+'\n')
    return files

def command(project, name, args):
    argv = ['node', str(CLI), *args, '--project-root', str(project), '--agents', 'claude,agentsmd', '--local-only', '--verbose']
    result = subprocess.run(argv, cwd=project, env=ENV, text=True, capture_output=True, timeout=30)
    write(project.parent / (name+'.log'), '$ '+ ' '.join(argv)+'\n'+result.stdout+result.stderr+f'\nEXIT {result.returncode}\n')
    return result

def scenario(name, root, child, flag=None, nested=True):
    case = OUT / name
    project = case / 'project'
    project.mkdir(parents=True)
    checks = []
    def check(name, good, actual=None):
        checks.append({'check':name, 'pass':bool(good), 'actual':actual})
    levels = [('',root)] + ([('child/',child)] if nested else [])
    originals = {}
    for prefix, enabled in levels:
        write(project/(prefix+'.ruler/ruler.toml'), 'default_agents = ["claude", "agentsmd"]\n' + ('nested = true\n' if nested and not prefix else '') + ('' if enabled is None else f'[backup]\nenabled = {str(enabled).lower()}\n'))
        for target in ['CLAUDE.md','AGENTS.md']:
            rel=prefix+target
            originals[rel]=f'# Original {prefix or "root/"}{target}\nPreserve this task-owned recovery text.\n'
            write(project/rel,originals[rel])
    write(project/'.gitignore', '# Existing ignore entry\nnode_modules/\n')
    snapshot(project, case/'00-before.json')
    apply_args=['apply','--no-mcp','--no-skills','--no-subagents', '--nested' if nested else '--no-nested']+([flag] if flag else [])
    for phase in [1,2]:
        for prefix,_ in levels:
            location = 'child' if prefix else 'root'
            write(project/(prefix+'.ruler/AGENTS.md'), f'# {location} shared rules revision {phase}\nRun the {location} parser checks before accepting changes. Revision {phase} requires exact recovery text.\n')
        run=command(project,f'{phase:02d}-apply',apply_args)
        check(f'apply {phase} exit',run.returncode==0,run.returncode)
        ignore=(read(project/'.gitignore') or '').splitlines()
        for prefix,enabled in levels:
            expected = True if flag=='--backup' else False if flag=='--no-backup' else True if enabled is None else enabled
            location='child' if prefix else 'root'
            for target in ['CLAUDE.md','AGENTS.md']:
                rel=prefix+target
                content=read(project/rel) or ''
                check(f'phase {phase} {rel} own current rule',f'# {location} shared rules revision {phase}' in content)
                check(f'phase {phase} {rel} no old revision',phase==1 or f'# {location} shared rules revision 1' not in content)
                other='root' if prefix else 'child'
                check(f'phase {phase} {rel} directory scope',f'# {other} shared rules revision' not in content)
                check(f'phase {phase} {rel} source marker','<!-- Source: .ruler/AGENTS.md -->' in content)
                backup=read(project/(rel+'.bak'))
                provenance=read(project/(rel+'.bak.ruler-generated'))
                check(f'phase {phase} {rel} backup presence', (backup is not None)==expected,backup is not None)
                check(f'phase {phase} {rel} original backup bytes', backup==originals[rel] if expected else backup is None)
                check(f'phase {phase} {rel} backup provenance',provenance==PROVENANCE if expected else provenance is None)
                for suffix in ['', '.bak','.bak.ruler-generated']:
                    wanted=True if not suffix else expected
                    check(f'phase {phase} ignore {rel}{suffix}',('/'+rel+suffix in ignore)==wanted)
        snap=snapshot(project,case/f'{phase:02d}-after-apply.json')
        allowed={'.gitignore'}
        for prefix,_ in levels:
            allowed.update(prefix+x for x in ['.ruler/ruler.toml','.ruler/AGENTS.md','CLAUDE.md','AGENTS.md','CLAUDE.md.bak','AGENTS.md.bak','CLAUDE.md.bak.ruler-generated','AGENTS.md.bak.ruler-generated'])
        check(f'phase {phase} only selected agent artifacts',set(snap)<=allowed,sorted(set(snap)-allowed))
    pre=snapshot(project,case/'03-before-revert.json')
    revert_args=['revert','--nested' if nested else '--no-nested','--keep-backups']
    dry=command(project,'03-revert-dry-run',revert_args+['--dry-run'])
    check('revert preview exit',dry.returncode==0,dry.returncode)
    check('preview did not mutate',snapshot(project,case/'03-after-dry-run.json')==pre)
    rev=command(project,'04-revert',revert_args)
    check('revert exit',rev.returncode==0,rev.returncode)
    for prefix,enabled in levels:
        expected=True if flag=='--backup' else False if flag=='--no-backup' else True if enabled is None else enabled
        for target in ['CLAUDE.md','AGENTS.md']:
            rel=prefix+target
            content=read(project/rel)
            check(f'revert {rel} first original or removed without backup',content==originals[rel] if expected else content is None,content)
            check(f'revert {rel} preserves backup',read(project/(rel+'.bak'))==originals[rel] if expected else not (project/(rel+'.bak')).exists())
            check(f'revert {rel} preserves provenance',read(project/(rel+'.bak.ruler-generated'))==PROVENANCE if expected else not (project/(rel+'.bak.ruler-generated')).exists())
    check('partial-agent revert leaves ignore block unchanged',read(project/'.gitignore')==pre['.gitignore'])
    snapshot(project,case/'04-after-revert.json')
    RESULTS.append({'scenario':name,'checks':checks,'pass':all(x['pass'] for x in checks)})

def unverified():
    case=OUT/'unverified-child-backup'; project=case/'project'; project.mkdir(parents=True)
    for prefix,enabled in [('',False),('child/',True)]:
        write(project/(prefix+'.ruler/AGENTS.md'),'# Task-owned shared source\n')
        write(project/(prefix+'.ruler/ruler.toml'),f'[backup]\nenabled = {str(enabled).lower()}\n')
        for target in ['CLAUDE.md','AGENTS.md']:
            write(project/(prefix+target),'# Original file remains safe\n')
    write(project/'child/CLAUDE.md.bak','# Unverified existing backup remains safe\n')
    before=snapshot(project,case/'00-before.json')
    r=command(project,'01-apply',['apply','--nested','--no-mcp','--no-skills','--no-subagents'])
    after=snapshot(project,case/'01-after.json')
    checks=[{'check':'refuses unverified backup with nonzero exit','pass':r.returncode!=0 and 'Refusing to use existing unverified backup file' in r.stderr,'actual':r.returncode},
            {'check':'existing unverified backup unmodified','pass':after.get('child/CLAUDE.md.bak')==before['child/CLAUDE.md.bak']},
            {'check':'child original output unmodified','pass':after.get('child/CLAUDE.md')==before['child/CLAUDE.md']},
            {'check':'does not forge backup provenance','pass':'child/CLAUDE.md.bak.ruler-generated' not in after}]
    rev=command(project,'02-revert',['revert','--nested','--keep-backups'])
    reverted=snapshot(project,case/'02-after-revert.json')
    checks.extend([
        {'check':'revert exit', 'pass':rev.returncode==0, 'actual':rev.returncode},
        {'check':'revert preserves unverified backup bytes', 'pass':reverted.get('child/CLAUDE.md.bak')==before['child/CLAUDE.md.bak']},
        {'check':'revert preserves original ungenerated target', 'pass':reverted.get('child/CLAUDE.md')==before['child/CLAUDE.md']},
        {'check':'revert does not forge provenance', 'pass':'child/CLAUDE.md.bak.ruler-generated' not in reverted},
    ])
    RESULTS.append({'scenario':'unverified-child-backup','checks':checks,'pass':all(x['pass'] for x in checks)})

def new_outputs():
    case=OUT/'new-rule-outputs'; project=case/'project'; project.mkdir(parents=True)
    for prefix,enabled in [('',False),('child/',True)]:
        write(project/(prefix+'.ruler/AGENTS.md'),'# Task-owned shared source\n')
        write(project/(prefix+'.ruler/ruler.toml'),f'[backup]\nenabled = {str(enabled).lower()}\n')
    snapshot(project,case/'00-before.json')
    r=command(project,'01-apply',['apply','--nested','--no-mcp','--no-skills','--no-subagents'])
    after=snapshot(project,case/'01-after.json')
    checks=[{'check':'apply exit','pass':r.returncode==0,'actual':r.returncode}]
    lines=after.get('.gitignore','').splitlines()
    targets=['CLAUDE.md','AGENTS.md','child/CLAUDE.md','child/AGENTS.md']
    for target in targets:
        checks.extend([
            {'check':target+' generated and tracked','pass':target in after and '/'+target in lines},
            {'check':target+' has no nonexistent backup/provenance','pass':target+'.bak' not in after and target+'.bak.ruler-generated' not in after},
            {'check':target+' no guessed backup ignore paths','pass':'/'+target+'.bak' not in lines and '/'+target+'.bak.ruler-generated' not in lines},
        ])
    r=command(project,'02-revert',['revert','--nested','--keep-backups'])
    reverted=snapshot(project,case/'02-after-revert.json')
    checks.append({'check':'revert removes only generated rule outputs','pass':r.returncode==0 and all(t not in reverted for t in targets)})
    RESULTS.append({'scenario':'new-rule-outputs','checks':checks,'pass':all(x['pass'] for x in checks)})

scenario('root-disabled-child-enabled',False,True)
scenario('root-enabled-child-disabled',True,False)
scenario('cli-backup',False,False,'--backup')
scenario('cli-no-backup',True,True,'--no-backup')
scenario('child-local-config-omits-backup',False,None)
scenario('single-enabled',True,None,nested=False)
scenario('single-disabled',False,None,nested=False)
unverified()
new_outputs()
write(OUT/'results.json',json.dumps(RESULTS,indent=2,ensure_ascii=False)+'\n')
for result in RESULTS:
    fails=[x for x in result['checks'] if not x['pass']]
    print(('PASS' if result['pass'] else 'FAIL')+' '+result['scenario']+f': {len(result["checks"])-len(fails)}/{len(result["checks"])} checks')
    for f in fails: print('  '+f['check']+': '+str(f.get('actual','')))
sys.exit(0 if all(x['pass'] for x in RESULTS) else 1)
